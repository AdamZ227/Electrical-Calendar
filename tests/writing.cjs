const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const app = fs.readFileSync('dist/app.js','utf8');
function setup(saved={}){
  const store = new Map(Object.entries(saved).map(([k,v])=>['ee-calendar.v2.'+k,JSON.stringify(v)]));
  const context=vm.createContext({localStorage:{getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v)},document:{getElementById:()=>({value:'',open:false})}});
  vm.runInContext(fs.readFileSync('dist/catalog.js','utf8')+'\n'+app.slice(0,app.indexOf("let view='list'")),context);
  return code=>vm.runInContext(code,context);
}
const run=setup();
assert.equal(run('activeCourses().filter(c=>isWriting(c.id)).length'),2);
assert.equal(run("prefs['WRIT 2130F'].enabled"),true);
assert.equal(run("prefs['WRIT 2130G'].enabled"),false);
const aise=setup({route:'aise'});
assert.equal(aise("prefs['WRIT 2130G'].enabled"),true);
assert.equal(aise("prefs['WRIT 2130F'].enabled"),false);
const migrated=setup({writingTerm:'G'});
assert.equal(migrated("prefs['WRIT 2130G'].enabled"),true);
assert.equal(migrated("prefs['WRIT 2130F'].enabled"),false);
const retained=setup({writingCheckboxes:true,prefs:{'WRIT 2130F':{enabled:true,section:''},'WRIT 2130G':{enabled:true,section:''}}});
assert.equal(retained("prefs['WRIT 2130G'].enabled&&prefs['WRIT 2130F'].enabled"),true);
run("manualRemoves=['WRIT 2130F']");
assert.equal(run('activeCourses().filter(c=>isWriting(c.id)).length'),1);
assert.equal(run('activeCourses().find(c=>isWriting(c.id)).id'),'WRIT 2130G');
run("manualRemoves=[];selectedRoute='bme'");
assert.equal(run('activeCourses().filter(c=>isWriting(c.id)).length'),0);
run("manualAdds=['WRIT 2130G']");
assert.equal(run('activeCourses().filter(c=>isWriting(c.id)).length'),2);
const filterCode=app.slice(app.indexOf('function filtered()'),app.indexOf('function setCourseEnabled('));
run('const course=id=>courses.find(c=>c.id===id);let admin=false;'+filterCode);
run("events=[{course:'WRIT 2130F',title:'Fall deadline',date:'2026-11-20',section:'all',type:'Assignment'},{course:'WRIT 2130G',title:'Winter deadline',date:'2027-02-20',section:'all',type:'Assignment'}]");
assert.equal(run('filtered().length'),1);
assert.equal(run('filtered()[0].title'),'Fall deadline');
run("prefs['WRIT 2130F'].enabled=false;prefs['WRIT 2130G'].enabled=true");
assert.equal(run('filtered().length'),1);
assert.equal(run('filtered()[0].title'),'Winter deadline');
run("prefs['WRIT 2130F'].enabled=true");
assert.equal(run('filtered().length'),2);
run("prefs['WRIT 2130F'].enabled=false;prefs['WRIT 2130G'].enabled=false");
assert.equal(run('filtered().length'),0);
console.log('Writing checkbox defaults, migration, removal and deadline filtering passed.');
